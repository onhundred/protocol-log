export function t(lang, key, ...args) {
  const v = lookup(WORDS[uiLang(lang)], key) ?? lookup(en, key);
  if (v === undefined) throw new Error(`No words for ${key}`);
  return typeof v === "function" ? v(...args) : v;
}

