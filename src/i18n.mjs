// Rule and write-error messages. The protocol code writes them in English, the language agents read.
// ruleText puts the ones a person sees on the owner's pages in the page's language; any other message stays English.

const ES_FIELDS = { name: "el nombre", doneWhen: "«listo cuando»", scope: "el alcance", question: "la pregunta", hypothesis: "la apuesta", learned: "lo aprendido", about: "tu línea" };
const esField = (f) => (f.startsWith("pending ") ? `${esField(f.slice(8))} pendiente` : ES_FIELDS[f] || f);
const esLang = (l) => es.languageNames[l] || l;

// Ordered: the first pattern that matches the whole message wins. $-groups come in as arguments.
const ES_ISSUES = [
  [/^has an em-dash\. Use a period, a comma or a colon\.$/, () => "tiene una raya larga (—). Usa un punto, una coma o dos puntos."],
  [/^has an exclamation mark\. The log states facts\.$/, () => "tiene un signo de exclamación. El log cuenta hechos."],
  [/^uses "(.+)", which VOICE\.md never uses\.$/, (w) => `usa «${w}», que VOICE.md nunca usa.`],
  [/^uses "(.+)", which guilts the reader\. State the fact and offer a next step\.$/, (w) => `usa «${w}», que culpa a quien lee. Di el hecho y ofrece un siguiente paso.`],
  [/^uses "(.+)", which is hype\. Say what happened, plainly\.$/, (w) => `usa «${w}», que exagera. Di lo que pasó, sin adornos.`],
  [/^uses "(.+)", a retired word\. Say loop or experiment instead\.$/, (w) => `usa «${w}», una palabra retirada. Di loop o experimento.`],
  [/^has (\d+) words\. A loop name has (\d+) or fewer, so it fits on the grid\.$/, (n, max) => `tiene ${n} palabras. Un nombre de loop tiene ${max} o menos, para que quepa en la cuadrícula.`],
  [/^starts with a failing verb \((.+)\)\. Name the result instead: .+\.$/, (v) => `empieza con un verbo que no nombra un resultado (${v}). Nombra el resultado: reservar, enviar, pagar, publicar.`],
  [/^has (\d+) words\. A loop scope has (\d+) or fewer\.$/, (n, max) => `tiene ${n} palabras. El alcance de un loop tiene ${max} o menos.`],
  [/^has (\d+) words\. Keep it to (\d+) or fewer\.$/, (n, max) => `tiene ${n} palabras. Usa ${max} o menos.`],
  [/^has (\d+) links\. The header shows (\d+) at most\.$/, (n, max) => `tiene ${n} enlaces. El encabezado muestra ${max} como máximo.`],
  [/^has 2 (.+) links\. Keep 1\.$/, (k) => `tiene 2 enlaces de ${k}. Deja 1.`],
  [/^(.+): "(.*)" is not a web address\.$/, (k, u) => `${k}: «${u}» no es una dirección web.`],
  [/^(.+): the address starts with https:\/\/\.$/, (k) => `${k}: la dirección empieza con https://.`],
  [/^(.+): the address is on (.+), not (.+)\.$/, (k, host, want) => `${k}: la dirección está en ${host}, no en ${want.replace(/ or /g, " o ")}.`],
];

const ES_RULES = [
  [/^(.+?) is missing in (\w+)\. Every public text needs each of the log's languages\.$/, (f, l) => `falta ${esField(f)} en ${esLang(l)}. Cada texto público necesita todos los idiomas del log.`],
  [/^(.+?) is missing\. Every public text needs each of the log's languages\.$/, (f) => `falta ${esField(f)}. Cada texto público necesita todos los idiomas del log.`],
  [/^about \((\w+)\) has (\d+) words\. Keep it to (\d+) or fewer\.$/, (l, n, max) => `tu línea (${l}) tiene ${n} palabras. Usa ${max} o menos.`],
  [/^(.+?) \((\w+)\) (.+)$/, (f, l, issue) => `${esField(f)} (${l}) ${esIssue(issue)}`],
  [/^(.+) is not a proposed loop\.$/, (c) => `${c} no es un loop propuesto.`],
  [/^nothing pending matches\. .+$/, () => "Nada pendiente coincide. Recarga la página para ver lo que espera."],
  [/^(.+) has no measured cost waiting\.$/, (c) => `${c} no tiene un costo medido esperando.`],
  [/^ownerName can't be empty: .+$/, () => "Tu nombre no puede quedar vacío: es el nombre que las visitas ven sobre tus números."],
  [/^the log already runs v(.+), the newest version in this code\.$/, (v) => `El log ya usa v${v}, la versión más nueva de este código.`],
  [/^v(.+) is already adopted\. It takes effect after check-in (\d+)\.$/, (v, c) => `La v${v} ya está adoptada. Entra en vigor después del check-in ${c}.`],
  [/^only the owner can do this\..*$/, () => "Solo la persona dueña del log puede hacer esto."],
];

const match = (table, text) => {
  for (const [re, say] of table) {
    const m = re.exec(text);
    if (m) return say(...m.slice(1));
  }
  return null;
};
const esIssue = (issue) => match(ES_ISSUES, issue) ?? issue;

// One rule message, without its "TARGET: " prefix.
export function ruleText(lang, text) {
  if (uiLang(lang) !== "es") return text;
  return match(ES_RULES, text) ?? match(ES_ISSUES, text) ?? text;
}

// A refused write from the writer: { error, violations? }. Violations are "TARGET: message" lines.
export function writeError(lang, r) {
  if (uiLang(lang) !== "es") return r.error;
  if (r.violations?.length)
    return `Rechazado: el cambio rompe el protocolo. ${r.violations
      .map((v) => {
        const at = v.indexOf(": ");
        return at < 0 ? ruleText(lang, v) : `${v.slice(0, at)}: ${ruleText(lang, v.slice(at + 2))}`;
      })
      .join(" ")}`;
  return ruleText(lang, r.error);
}
