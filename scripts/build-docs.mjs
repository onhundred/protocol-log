// Writes src/docs.mjs from docs/, so the Worker can serve the protocol, LOOPS.md, VOICE.md and PLAYBOOK.md as
// MCP resources without reading files at runtime. Run it after editing anything in docs/.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import P from "../protocol.json" with { type: "json" };
import { checkFile, readDebt, report } from "./voicecheck.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = { protocol: "protocol.md", loops: "LOOPS.md", voice: "VOICE.md", playbook: "PLAYBOOK.md" };
export const DOCS_MODULE = join(root, "src", "docs.mjs");

export async function docsModule() {
  const texts = {};
  for (const [key, file] of Object.entries(DOCS)) texts[key] = await readFile(join(root, "docs", file), "utf8");
  const version = /^# Onhundred Protocol v(\S+)/.exec(texts.protocol)?.[1];
  if (version !== P.version)
    throw new Error(`docs/protocol.md is v${version ?? "?"}, but protocol.json enforces v${P.version}. Update one to match.`);
  return (
    "// Generated by scripts/build-docs.mjs. Do not edit; edit docs/ and run npm run docs.\n" +
    Object.entries(texts)
      .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`)
      .join("\n") +
    "\n"
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const debt = await readDebt();
  const voice = report(await Promise.all(Object.values(DOCS).map((f) => checkFile(`docs/${f}`, debt))));
  if (voice) {
    console.log(voice);
    console.log("\nNot built: rewrite these in plain English (VOICE.md, rule zero).");
    process.exit(1);
  }
  await writeFile(DOCS_MODULE, await docsModule());
  console.log("wrote src/docs.mjs from docs/ for protocol", `v${P.version}`);
}
